create table if not exists public.study_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject text not null check (char_length(subject) between 1 and 100),
  topic text check (topic is null or char_length(topic) <= 180),
  minutes integer not null check (minutes between 1 and 1440),
  questions integer not null default 0 check (questions >= 0),
  correct integer not null default 0 check (correct >= 0 and correct <= questions),
  notes text check (notes is null or char_length(notes) <= 1000),
  studied_on date not null default current_date,
  created_at timestamptz not null default now()
);
create index if not exists study_sessions_user_date_idx on public.study_sessions (user_id, studied_on desc, created_at desc);
alter table public.study_sessions enable row level security;
drop policy if exists "Read own study sessions" on public.study_sessions;
create policy "Read own study sessions" on public.study_sessions for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Insert own study sessions" on public.study_sessions;
create policy "Insert own study sessions" on public.study_sessions for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Update own study sessions" on public.study_sessions;
create policy "Update own study sessions" on public.study_sessions for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Delete own study sessions" on public.study_sessions;
create policy "Delete own study sessions" on public.study_sessions for delete to authenticated using (auth.uid() = user_id);
revoke all on public.study_sessions from anon;
grant select, insert, update, delete on public.study_sessions to authenticated;
grant usage, select on sequence public.study_sessions_id_seq to authenticated;
